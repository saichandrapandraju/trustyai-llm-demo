def _get_javascript() -> str:
    """Return embedded JavaScript for interactivity."""
    return """
        // Initialize collapsibles
        document.querySelectorAll('.collapsible').forEach(button => {
            button.addEventListener('click', function() {
                this.classList.toggle('active');
                const content = this.nextElementSibling;
                content.classList.toggle('active');
            });
        });
        
        // Get filtered rows based on current filter settings
        function getFilteredRows() {
            const probeFilter = document.getElementById('probe-filter')?.value || '';
            const statusFilter = document.getElementById('status-filter')?.value || '';
            const searchText = document.getElementById('search-filter')?.value.toLowerCase() || '';
            
            const allRows = document.querySelectorAll('.attempt-row');
            const filtered = [];
            
            allRows.forEach(row => {
                const probe = row.dataset.probe || '';
                const status = row.dataset.status || '';
                const text = row.textContent.toLowerCase();
                
                const matchesProbe = !probeFilter || probe === probeFilter;
                const matchesStatus = !statusFilter || status === statusFilter;
                const matchesSearch = !searchText || text.includes(searchText);
                
                if (matchesProbe && matchesStatus && matchesSearch) {
                    filtered.push(row);
                }
            });
            
            return filtered;
        }
        
        // Apply pagination to current filtered results
        function applyPagination() {
            filteredRows = getFilteredRows();
            const totalRows = document.querySelectorAll('.attempt-row').length;
            const totalPages = Math.ceil(filteredRows.length / pageSize);
            
            // Ensure current page is valid
            if (currentPage > totalPages) {
                currentPage = Math.max(1, totalPages);
            }
            
            // Hide all rows first
            document.querySelectorAll('.attempt-row, .details-row').forEach(row => {
                row.style.display = 'none';
            });
            
            // Show only current page rows
            const startIdx = (currentPage - 1) * pageSize;
            const endIdx = Math.min(startIdx + pageSize, filteredRows.length);
            
            for (let i = startIdx; i < endIdx; i++) {
                filteredRows[i].style.display = '';
            }
            
            // Update pagination info
            updatePaginationInfo(filteredRows.length, totalRows);
            updatePaginationButtons(totalPages);
        }
        
        // Update pagination info text
        function updatePaginationInfo(filteredCount, totalCount) {
            const countEl = document.getElementById('visible-count');
            if (countEl) {
                const startIdx = (currentPage - 1) * pageSize + 1;
                const endIdx = Math.min(currentPage * pageSize, filteredCount);
                const totalPages = Math.ceil(filteredCount / pageSize);
                
                if (filteredCount === 0) {
                    countEl.innerHTML = '<span style="color: var(--color-fail);">No attempts match your filters</span> <span style="color: var(--color-warning);">- Try adjusting your filters</span>';
                } else {
                    countEl.innerHTML = `Showing <strong>${startIdx}-${endIdx}</strong> of <strong>${filteredCount}</strong> attempts (Page ${currentPage} of ${totalPages})`;
                }
            }
        }
        
        // Update pagination buttons
        function updatePaginationButtons(totalPages) {
            const prevBtn = document.getElementById('prev-page');
            const nextBtn = document.getElementById('next-page');
            const pageInfo = document.getElementById('page-info');
            
            if (prevBtn) prevBtn.disabled = currentPage === 1;
            if (nextBtn) nextBtn.disabled = currentPage >= totalPages || totalPages === 0;
            if (pageInfo) pageInfo.textContent = `Page ${currentPage} of ${totalPages}`;
            
            // Update page number buttons
            renderPageNumbers(totalPages);
        }
        
        // Render page number buttons
        function renderPageNumbers(totalPages) {
            renderPageNumbersInContainer('page-numbers', totalPages);
            renderPageNumbersInContainer('page-numbers-bottom', totalPages);
        }
        
        function renderPageNumbersInContainer(containerId, totalPages) {
            const container = document.getElementById(containerId);
            if (!container) return;
            
            container.innerHTML = '';
            
            // Show max 7 page buttons
            let startPage = Math.max(1, currentPage - 3);
            let endPage = Math.min(totalPages, startPage + 6);
            
            // Adjust if we're near the end
            if (endPage - startPage < 6) {
                startPage = Math.max(1, endPage - 6);
            }
            
            // First page
            if (startPage > 1) {
                const btn = createPageButton(1, '1');
                container.appendChild(btn);
                if (startPage > 2) {
                    const dots = document.createElement('span');
                    dots.textContent = '...';
                    dots.style.padding = '6px 12px';
                    dots.style.color = 'var(--text-secondary)';
                    container.appendChild(dots);
                }
            }
            
            // Page buttons
            for (let i = startPage; i <= endPage; i++) {
                const btn = createPageButton(i, i.toString());
                container.appendChild(btn);
            }
            
            // Last page
            if (endPage < totalPages) {
                if (endPage < totalPages - 1) {
                    const dots = document.createElement('span');
                    dots.textContent = '...';
                    dots.style.padding = '6px 12px';
                    dots.style.color = 'var(--text-secondary)';
                    container.appendChild(dots);
                }
                const btn = createPageButton(totalPages, totalPages.toString());
                container.appendChild(btn);
            }
        }
        
        // Create page button
        function createPageButton(pageNum, label) {
            const btn = document.createElement('button');
            btn.textContent = label;
            btn.className = 'page-button' + (pageNum === currentPage ? ' active' : '');
            btn.onclick = () => goToPage(pageNum);
            return btn;
        }
        
        // Navigation functions
        function goToPage(page) {
            currentPage = page;
            applyPagination();
        }
        
        function previousPage() {
            if (currentPage > 1) {
                currentPage--;
                applyPagination();
            }
        }
        
        function nextPage() {
            const totalPages = Math.ceil(filteredRows.length / pageSize);
            if (currentPage < totalPages) {
                currentPage++;
                applyPagination();
            }
        }
        
        function changePageSize() {
            const select = document.getElementById('page-size');
            if (select) {
                pageSize = parseInt(select.value);
                currentPage = 1; // Reset to first page
                applyPagination();
            }
        }
        
        // Filter and apply pagination
        function filterAttempts() {
            currentPage = 1; // Reset to first page when filtering
            applyPagination();
        }
        
        // Expand row details
        function toggleRow(uuid) {
            const details = document.getElementById('details-' + uuid);
            if (details) {
                const isHidden = details.style.display === 'none' || details.style.display === '';
                details.style.display = isHidden ? 'table-row' : 'none';
            }
        }
        
        // Initialize pagination on load
        document.addEventListener('DOMContentLoaded', function() {
            applyPagination();
        });
        
        // If DOM is already loaded
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', () => applyPagination());
        } else {
            applyPagination();
        }
        
        console.log('Garak Enhanced Report with pagination loaded successfully');
    """


