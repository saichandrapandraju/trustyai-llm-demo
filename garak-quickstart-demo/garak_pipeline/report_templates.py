def generate_html_report(data: Dict[str, Any], title: str = "Garak Security Scan Report") -> str:
    """
    Generate complete HTML report from parsed data.
    
    Args:
        data: Parsed report data from GarakReportProcessor
        title: Report title
        
    Returns:
        Complete HTML document as string
    """
    metadata = data["metadata"]
    summary = data["summary"]
    probes = data["probes"]
    attempts = data["attempts"]
    vulnerable_highlights = data["vulnerable_highlights"]
    config = data.get("config", {})
    filtered_count = data.get("filtered_count", 0)
    
    # Generate sections
    executive_summary_html = _generate_executive_summary(metadata, summary, config, filtered_count)
    charts_html = _generate_charts_section(summary, probes, attempts)
    probes_table_html = _generate_probes_table(probes)
    # Removed vulnerable_highlights_html - redundant and takes too much space
    attempts_table_html = _generate_attempts_explorer(attempts)
    config_html = _generate_config_section(config)
    
    # Embed data for JavaScript
    data_json = json.dumps({
        "summary": summary,
        "probes": probes,
        "attempts": [
            {**a, "detector_scores": a["detector_scores"]} 
            for a in attempts
        ]
    })
    
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{html.escape(title)}</title>
    {_get_styles()}
</head>
<body>
    <div class="container">
        <header>
            <h1>🛡️ {html.escape(title)}</h1>
            <p class="subtitle">Generated on {metadata.get('start_time', 'Unknown')}</p>
        </header>
        
        {executive_summary_html}
        {charts_html}
        {probes_table_html}
        {attempts_table_html}
        {config_html}
        
        <footer>
            <p>Generated by Garak {metadata.get('garak_version', 'unknown')} | Run ID: {metadata.get('run_id', 'unknown')}</p>
        </footer>
    </div>
    
    <script>
    // Embedded data
    const reportData = {data_json};
    
    // Pagination state
    let currentPage = 1;
    let pageSize = 50;
    let filteredRows = [];
    
    {_get_javascript()}
    </script>
</body>
</html>"""


