def _generate_vulnerable_highlights(vulnerable: List[Dict]) -> str:
    """Generate vulnerable attempts highlights."""
    if not vulnerable:
        return """
        <section class="section">
            <h2 class="section-title">✅ No Vulnerabilities Detected</h2>
            <p>All attempts passed security checks. Great job!</p>
        </section>
        """
    
    cards_html = []
    for attempt in vulnerable[:10]:  # Show top 10
        max_score = max(attempt["detector_scores"].values()) if attempt["detector_scores"] else 0.0
        is_critical = max_score > 0.7
        card_class = "vulnerable-card critical" if is_critical else "vulnerable-card"
        
        detector_scores_html = "".join([
            f"""
            <div class="detector-score-item">
                <span>{html.escape(detector)}</span>
                <span style="font-weight: bold; color: var(--color-fail);">{score:.3f}</span>
            </div>
            """
            for detector, score in attempt["detector_scores"].items()
        ])
        
        cards_html.append(f"""
        <div class="{card_class}">
            <div class="vulnerable-header">
                <span class="probe-name">🔴 {html.escape(attempt['probe'])}</span>
                <span class="score-badge">{max_score:.3f}</span>
            </div>
            
            <div style="font-size: 0.9rem; color: var(--text-secondary); margin-bottom: 10px;">
                <strong>Goal:</strong> {html.escape(attempt['goal'])}
            </div>
            
            <div class="prompt-response">
                <div class="prompt-label">Prompt:</div>
                <div class="prompt-text">{html.escape(attempt['prompt'][:500])}</div>
            </div>
            
            <div class="prompt-response">
                <div class="response-label">Response:</div>
                <div class="response-text">{html.escape(attempt['response'][:500])}</div>
            </div>
            
            {f'<div class="detector-scores"><strong>Detector Scores:</strong>{detector_scores_html}</div>' if detector_scores_html else ''}
        </div>
        """)
    
    return f"""
    <section class="section">
        <h2 class="section-title">⚠️ Vulnerable Attempts ({len(vulnerable)} total)</h2>
        <p style="margin-bottom: 20px; color: var(--text-secondary);">
            Showing the most concerning vulnerabilities detected during the scan.
        </p>
        {"".join(cards_html)}
    </section>
    """


